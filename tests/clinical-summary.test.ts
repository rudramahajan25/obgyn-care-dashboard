import assert from 'node:assert/strict';
import { patients } from '../src/data/mockData';
import { getPatientAiSummary, mergeOllamaSummary } from '../src/data/patientAiSummaries';
import { maternalObservations, consentReminders, currentCtgSummary } from '../src/utils/summaryObservations';
import { buildPatientChartContext } from '../src/utils/patientChartContext';

const critical = structuredClone(patients.find(p => p.id === 'p5')!);
const summary = getPatientAiSummary(critical, null);
assert.equal(maternalObservations(critical).length, 5);
assert.match(currentCtgSummary(critical), /FHR 155 bpm/);
assert.doesNotMatch(currentCtgSummary(critical), /tachycardia|Category III|accelerations present/);
critical.vitals.pulse = 117;
critical.vitals.spo2 = 92;
assert.equal(maternalObservations(critical)[1].value, '117');
assert.equal(maternalObservations(critical)[2].value, '92');
const chart = JSON.parse(buildPatientChartContext(critical, null));
assert.equal(chart.currentMaternalVitals.pulse, '117 bpm');
assert.equal(chart.currentMaternalVitals.spo2, '92%');
assert.match(chart.consentStatus, /not recorded/);
const reminders = consentReminders(critical, summary.immediatePlan).join(' ');
assert.match(reminders, /anaesthetic consent/);
assert.match(reminders, /does not replace/);
assert.match(reminders, /not recorded/);
assert.match(reminders, /authorised representative/);
const induction = patients.find(p => p.id === 'p4')!;
assert.match(consentReminders(induction, getPatientAiSummary(induction, null).immediatePlan).join(' '), /planned induction/);
const postpartum = patients.find(p => p.id === 'p3')!;
assert.match(currentCtgSummary(postpartum), /not applicable/);
assert.doesNotMatch(consentReminders(postpartum, []).join(' '), /operative delivery|planned induction/);
const previousLoss = patients.find(p => p.id === 'p6')!;
assert.equal(getPatientAiSummary(previousLoss, null).pelvisAssessment, undefined);
const merged = mergeOllamaSummary(summary, { ctgStatus: 'invented category', admissionPvFindings: 'invented exam' });
assert.equal(merged.ctgStatus, summary.ctgStatus);
assert.equal(merged.admissionPvFindings, summary.admissionPvFindings);
console.log('Clinical summary checks passed.');

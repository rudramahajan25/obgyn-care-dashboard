function generateCTG(): Patient["ctg"]["points"] {
  const points: Patient["ctg"]["points"] = [];
  for (let i = 0; i <= 50; i += 2) {
    points.push({
      time: i,
      fhr: 135 + Math.sin(i / 8) * 12 + Math.random() * 4,
      uc: Math.max(0, Math.sin(i / 6) * 40 + (i > 20 && i < 35 ? 30 : 0)),
      fm: i % 15 === 0 ? 1 : 0,
    });
  }
  return points;
}

